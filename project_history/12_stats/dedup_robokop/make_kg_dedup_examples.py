#!/usr/bin/env python3
import os
import pandas as pd

BASE = os.path.expanduser("~/gpt/12_stats/dedup_robokop")
PER_Q = os.path.join(BASE, "robokop_dedup.per_question_counts.tsv")
TRIPLES_RAW = os.path.join(BASE, "robokop_triples.tsv")
OUT_TEX = os.path.join(BASE, "kg_dedup_examples.tex")

N_QUESTIONS = 5          # pick 4-5 as you requested
ROWS_PER_QUESTION = 1    # 1 representative duplicated triple per question (keeps table short)

def escape_latex(s: str) -> str:
    if s is None:
        return ""
    s = str(s)
    # minimal escaping
    return (s.replace("\\", "\\textbackslash{}")
              .replace("&", "\\&")
              .replace("%", "\\%")
              .replace("$", "\\$")
              .replace("#", "\\#")
              .replace("_", "\\_")
              .replace("{", "\\{")
              .replace("}", "\\}")
              .replace("~", "\\textasciitilde{}")
              .replace("^", "\\textasciicircum{}"))

# --- Load per-question counts and select questions with duplicates ---
counts = pd.read_csv(PER_Q, sep="\t")
if "dup_rows_exact" not in counts.columns:
    raise ValueError(f"Expected column dup_rows_exact in {PER_Q}, found: {list(counts.columns)}")

dedup_qs = counts[counts["dup_rows_exact"] > 0].copy()
if dedup_qs.empty:
    raise ValueError("No questions with dup_rows_exact > 0 found. Nothing to sample.")

# Choose the most affected questions by exact duplicates removed
dedup_qs = dedup_qs.sort_values("dup_rows_exact", ascending=False).head(N_QUESTIONS)
chosen_qids = dedup_qs["question_id"].tolist()

# --- Load raw triples ---
raw = pd.read_csv(TRIPLES_RAW, sep="\t")

# Infer expected columns
# We try typical names; adjust here if yours differ.
colmap = {c.lower(): c for c in raw.columns}

def need_col(*cands):
    for cand in cands:
        for k, orig in colmap.items():
            if cand in k:
                return orig
    raise ValueError(f"Could not infer columns from {list(raw.columns)}; please set column names manually.")

qid_col = need_col("question_id")
subj_col = need_col("subject")
pred_col = need_col("predicate")
obj_col  = need_col("object")

rows_out = []
for qid in chosen_qids:
    r = raw[raw[qid_col] == qid].copy()
    if r.empty:
        continue

    # Count duplicates of identical triples within this question
    grp = (r.groupby([subj_col, pred_col, obj_col])
             .size()
             .reset_index(name="raw_multiplicity"))
    grp = grp[grp["raw_multiplicity"] > 1].sort_values("raw_multiplicity", ascending=False)

    # If no duplicates found in raw triples for some reason, skip
    if grp.empty:
        continue

    for _, row in grp.head(ROWS_PER_QUESTION).iterrows():
        rows_out.append({
            "question_id": qid,
            "subject": row[subj_col],
            "predicate": row[pred_col],
            "object": row[obj_col],
            "raw_multiplicity": int(row["raw_multiplicity"])
        })

if not rows_out:
    raise ValueError("Could not extract any duplicated triples. Check TRIPLES_RAW column names/content.")

# --- Write LaTeX table snippet ---
lines = []
lines.append("% Auto-generated by make_kg_dedup_examples.py")
lines.append("\\begin{table}[t]")
lines.append("\\centering")
lines.append("\\caption{Representative examples of redundant ROBOKOP triples removed by within-pair exact deduplication. Each row shows a triple that appeared multiple times in the raw output for a given entity pair and was retained once in the deduplicated baseline.}")
lines.append("\\label{tab:kg_dedup_examples}")
lines.append("\\begin{tabular}{l p{0.28\\textwidth} p{0.22\\textwidth} p{0.28\\textwidth} r}")
lines.append("\\hline")
lines.append("Question & Subject (CURIE) & Predicate & Object (CURIE) & Raw mult. \\\\")
lines.append("\\hline")

for rr in rows_out:
    lines.append(
        f"{escape_latex(rr['question_id'])} & "
        f"{escape_latex(rr['subject'])} & "
        f"{escape_latex(rr['predicate'])} & "
        f"{escape_latex(rr['object'])} & "
        f"{rr['raw_multiplicity']} \\\\"
    )

lines.append("\\hline")
lines.append("\\end{tabular}")
lines.append("\\end{table}")

with open(OUT_TEX, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"[OK] Wrote LaTeX dedup examples table to: {OUT_TEX}")
print("Include it in LaTeX with: \\input{.../kg_dedup_examples.tex}")

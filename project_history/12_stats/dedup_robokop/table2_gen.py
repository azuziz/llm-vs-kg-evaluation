#!/usr/bin/env python3
import os
import pandas as pd

BASE = os.path.expanduser("~/gpt/12_stats/dedup_robokop")
PER_Q = os.path.join(BASE, "robokop_dedup.per_question_counts.tsv")
OUT_TEX = os.path.join(BASE, "kg_edge_count_summary_stats.tex")

df = pd.read_csv(PER_Q, sep="\t")

raw_col = "n_rows_total"
dedup_col = "n_unique_exact"
for c in [raw_col, dedup_col]:
    if c not in df.columns:
        raise ValueError(f"Expected {c} in {PER_Q}, found {list(df.columns)}")

def stats(series):
    s = series.astype(float)
    return {
        "min": s.min(),
        "q1": s.quantile(0.25),
        "median": s.median(),
        "mean": s.mean(),
        "q3": s.quantile(0.75),
        "max": s.max(),
    }

raw_stats = stats(df[raw_col])
dedup_stats = stats(df[dedup_col])

def fmt(x):
    # edge counts are integers, but keep mean as 2 decimals
    if float(x).is_integer():
        return str(int(x))
    return f"{x:.2f}"

lines = []
lines.append("% Auto-generated by make_kg_edge_count_summary_stats.py")
lines.append("\\begin{table}[t]")
lines.append("\\centering")
lines.append("\\caption{Baseline KG edge counts per entity pair before and after exact triple deduplication (n=163).}")
lines.append("\\label{tab:kg_edge_count_stats}")
lines.append("\\begin{tabular}{lrr}")
lines.append("\\hline")
lines.append("Statistic & Raw edges/pair & Deduplicated edges/pair \\\\")
lines.append("\\hline")
lines.append(f"Minimum & {fmt(raw_stats['min'])} & {fmt(dedup_stats['min'])} \\\\")
lines.append(f"1st quartile (Q1) & {fmt(raw_stats['q1'])} & {fmt(dedup_stats['q1'])} \\\\")
lines.append(f"Median & {fmt(raw_stats['median'])} & {fmt(dedup_stats['median'])} \\\\")
lines.append(f"Mean & {fmt(raw_stats['mean'])} & {fmt(dedup_stats['mean'])} \\\\")
lines.append(f"3rd quartile (Q3) & {fmt(raw_stats['q3'])} & {fmt(dedup_stats['q3'])} \\\\")
lines.append(f"Maximum & {fmt(raw_stats['max'])} & {fmt(dedup_stats['max'])} \\\\")
lines.append("\\hline")
lines.append("\\end{tabular}")
lines.append("\\end{table}")

with open(OUT_TEX, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"[OK] Wrote LaTeX summary stats table to: {OUT_TEX}")
print("Include it with: \\input{.../kg_edge_count_summary_stats.tex}")

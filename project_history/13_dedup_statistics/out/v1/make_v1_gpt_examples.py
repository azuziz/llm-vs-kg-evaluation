#!/usr/bin/env python3
import os
import pandas as pd

V1_DIR = os.path.expanduser("~/gpt/13_dedup_statistics/out/v1")
PER_RUN = os.path.join(V1_DIR, "per_run_metrics.tsv")
OUT_TEX = os.path.join(V1_DIR, "gpt_run_examples.tex")

df = pd.read_csv(PER_RUN, sep="\t")

cols_lower = {c.lower(): c for c in df.columns}

def find_col(candidates):
    for cand in candidates:
        for k, orig in cols_lower.items():
            if cand in k:
                return orig
    return None

# Try to infer common columns
qid_col = find_col(["question_id"])
run_col = find_col(["run", "run_index", "sample"])
pred_n_col = find_col(["n_pred", "pred_edges", "gpt_edges", "num_pred", "n_edges_pred", "edges_pred"])
match_n_col = find_col(["n_match", "matched_edges", "num_match", "n_edges_match", "correct_edges"])

# Optional: sometimes the TSV contains a JSON string of edges or a file path
edges_json_col = find_col(["edges_json", "edges", "prediction_json", "raw_json"])
raw_path_col = find_col(["raw_path", "output_path", "response_path", "file"])

for need, name in [(qid_col, "question_id"), (pred_n_col, "pred edge count"), (match_n_col, "matched edge count")]:
    if need is None:
        raise ValueError(f"Could not infer {name} column from: {list(df.columns)}\n"
                         "Open per_run_metrics.tsv and set the column names manually in the script.")

# Pick one run each:
# 1) empty output: pred=0
# 2) non-matching output: pred>0 and match=0
# 3) partially correct: pred>0 and 0<match<pred
empty = df[df[pred_n_col] == 0].head(1)
wrong = df[(df[pred_n_col] > 0) & (df[match_n_col] == 0)].head(1)
partial = df[(df[pred_n_col] > 0) & (df[match_n_col] > 0) & (df[match_n_col] < df[pred_n_col])].head(1)

def row_to_id(r):
    q = r[qid_col]
    run = r[run_col] if run_col else "NA"
    return f"{q}, run={run}"

def extract_payload(r):
    if edges_json_col and pd.notna(r.get(edges_json_col, None)):
        s = str(r[edges_json_col])
        return s[:1200] + ("..." if len(s) > 1200 else "")
    if raw_path_col and pd.notna(r.get(raw_path_col, None)):
        p = os.path.join(V1_DIR, str(r[raw_path_col])) if not os.path.isabs(str(r[raw_path_col])) else str(r[raw_path_col])
        if os.path.exists(p):
            txt = open(p, "r", encoding="utf-8", errors="ignore").read()
            txt = txt.strip().replace("\t", "  ")
            return txt[:1200] + ("..." if len(txt) > 1200 else "")
        return f"[raw output path not found: {p}]"
    return "[No raw edge payload available in per_run_metrics.tsv]"

blocks = []
def add_block(title, subdf):
    if subdf.empty:
        blocks.append((title, "[No example found under this criterion]"))
        return
    r = subdf.iloc[0]
    ident = row_to_id(r)
    pred = int(r[pred_n_col])
    match = int(r[match_n_col])
    payload = extract_payload(r)
    blocks.append((title, f"Identifier: {ident}\nPredicted edges: {pred}\nMatched edges: {match}\n\n{payload}"))

add_block("Empty output example (|M| = 0)", empty)
add_block("Non-matching output example (|M| > 0 and |M ∩ G| = 0)", wrong)
add_block("Partially correct output example (0 < |M ∩ G| < |M|)", partial)

# Write a LaTeX snippet using verbatim blocks
lines = []
lines.append("% Auto-generated by make_v1_gpt_examples.py")
lines.append("\\begin{table}[t]")
lines.append("\\centering")
lines.append("\\caption{Representative v1 model outputs illustrating common outcome types: empty output, non-matching output, and partially correct output.}")
lines.append("\\label{tab:v1_gpt_examples}")
lines.append("\\begin{tabular}{p{0.25\\textwidth} p{0.68\\textwidth}}")
lines.append("\\hline")
lines.append("Example type & Output excerpt \\\\")
lines.append("\\hline")

for title, text in blocks:
    # Use \verb is too small; use minipage + verbatim
    text = text.replace("\\", "\\textbackslash{}")  # avoid breaking LaTeX
    lines.append(f"\\textbf{{{title}}} & \\begin{{minipage}}[t]{{0.68\\textwidth}}\\vspace{{0.5ex}}\\small\\begin{{verbatim}}\n{text}\n\\end{{verbatim}}\\end{{minipage}} \\\\")
    lines.append("\\hline")

lines.append("\\end{tabular}")
lines.append("\\end{table}")

with open(OUT_TEX, "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")

print(f"[OK] Wrote LaTeX GPT examples table to: {OUT_TEX}")
print("Include it with: \\input{.../gpt_run_examples.tex}")
